def framework() -> str:
    user = app.storage.user.get('user') or {}
    org_fw = user.get('frameworks')
    fw_list = []
    if isinstance(org_fw, (list, tuple)):
        fw_list = [str(f).lower().strip() for f in org_fw if f]
    elif isinstance(org_fw, str):
        fw_list = [f.strip().lower() for f in org_fw.split(',') if f.strip()]

    if fw_list == ['ohada']:
        return 'ohada'
    if fw_list == ['ifrs']:
        return 'ifrs'
    stored = app.storage.user.get('framework')
    if stored in ('ohada', 'ifrs'):
        return stored
    return 'ohada'


def lang() -> str:
    # Rule: IFRS framework strictly has English only
    if framework() == 'ifrs':
        return 'en'
    stored = app.storage.user.get('lang')
    if stored in ('en', 'fr'):
        return stored
    user = app.storage.user.get('user') or {}
    locale = str(user.get('locale') or 'en').lower()[:2]
    return locale if locale in ('en', 'fr') else 'en'


def set_lang(code: str) -> None:
    # Rule: If framework is IFRS, language is permanently locked to English
    if framework() == 'ifrs':
        app.storage.user['lang'] = 'en'
        return
    if code in ('en', 'fr'):
        app.storage.user['lang'] = code


def set_framework(code: str) -> None:
    if code in ('ohada', 'ifrs'):
        app.storage.user['framework'] = code
        if code == 'ifrs':
            app.storage.user['lang'] = 'en'


def t(key: str, **kwargs) -> str:
    pack = STRINGS.get(lang()) or STRINGS['en']
    text = pack.get(key) or STRINGS['en'].get(key) or key
    return text.format(**kwargs) if kwargs else text


def status_label(value) -> str:
    if value is None or value == '':
        return ''
    key = f'status.{str(value).lower()}'
    labelled = t(key)
    return labelled if labelled != key else str(value).replace('_', ' ').capitalize()


def domain_label(value) -> str:
    if not value:
        return ''
    key = f'domain.{value}'
    labelled = t(key)
    return labelled if labelled != key else str(value).replace('_', ' ').capitalize()


def account_label(row: dict) -> str:
    """Language-appropriate chart-of-accounts name (SYSCOHADA FR / English)."""
    return bilingual(row) or str(row.get('code') or '')


def bilingual(row: dict, fr_keys=('label', 'name'), en_keys=('label_en', 'name_en', 'label_fr')) -> str:
    """
    Picks the language-appropriate field from an API row.

    OHADA templates store French in `label` and English in `label_en`.
    IFRS templates store English in `label` and French in `label_fr`.
    """
    if not row:
        return ''
    if lang() == 'fr':
        for key in ('label_fr', 'name') + tuple(fr_keys):
            if row.get(key):
                return str(row[key])
    else:
        for key in ('label_en', 'name_en', 'label') + tuple(en_keys):
            if row.get(key):
                return str(row[key])
    return str(row.get('label') or row.get('name') or '')
