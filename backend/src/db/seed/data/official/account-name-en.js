export function englishAccountName(name, fallback = name) {
  if (!name) return fallback;
  if (ACCOUNT_NAME_EN[name]) return ACCOUNT_NAME_EN[name];
  const folded = name.normalize('NFC');
  return ACCOUNT_NAME_EN[folded] || fallback;
}
