  cost_center_id INT UNSIGNED NULL,
  address        VARCHAR(300) NULL,
  is_active      TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  UNIQUE KEY uq_al_code (org_id, code),
  KEY ix_al_parent (parent_id),
  CONSTRAINT fk_al_org    FOREIGN KEY (org_id) REFERENCES organizations (id) ON DELETE CASCADE,
  CONSTRAINT fk_al_parent FOREIGN KEY (parent_id) REFERENCES asset_locations (id) ON DELETE SET NULL,
