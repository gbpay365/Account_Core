  location_id            INT UNSIGNED NULL,
  custodian_user_id      INT UNSIGNED NULL,
  is_mobile              TINYINT(1)   NOT NULL DEFAULT 1,
  -- status
  status                 ENUM('draft','in_stock','installing','in_service','under_maintenance','awaiting_parts','calibration_overdue','quarantined','out_of_service','pending_disposal','disposed') NOT NULL DEFAULT 'draft',
  asset_condition        ENUM('new','good','fair','poor','unserviceable') NOT NULL DEFAULT 'new',
  criticality            ENUM('low','medium','high','critical') NOT NULL DEFAULT 'medium',
  use_restricted         TINYINT(1)   NOT NULL DEFAULT 0,
  restriction_reason     VARCHAR(300) NULL,
  -- acquisition (FR-AM-010)
  acquisition_date       DATE         NULL,
  capitalization_date    DATE         NULL,
  in_service_date        DATE         NULL,
  funding_source         ENUM('purchase','donation','grant','lease','transfer','own_construction') NOT NULL DEFAULT 'purchase',
  funding_reference      VARCHAR(120) NULL,
  donor_name             VARCHAR(200) NULL,
  supplier_id            INT UNSIGNED NULL,
  purchase_order_id      INT UNSIGNED NULL,
  supplier_invoice_id    INT UNSIGNED NULL,
  currency               CHAR(3)      NOT NULL DEFAULT 'XAF',
  acquisition_cost       DECIMAL(20,2) NOT NULL DEFAULT 0,
  incidental_costs       DECIMAL(20,2) NOT NULL DEFAULT 0,
  is_capitalized         TINYINT(1)   NOT NULL DEFAULT 0,
  acquisition_entry_id   INT UNSIGNED NULL,
  -- OHADA basis
  ohada_cost             DECIMAL(20,2) NOT NULL DEFAULT 0,
  ohada_salvage          DECIMAL(20,2) NOT NULL DEFAULT 0,
  ohada_useful_life_months SMALLINT UNSIGNED NOT NULL DEFAULT 60,
  ohada_method           ENUM('straight_line','declining_balance') NOT NULL DEFAULT 'straight_line',
  ohada_declining_factor DECIMAL(6,3) NOT NULL DEFAULT 1.000,
  ohada_accum_depr       DECIMAL(20,2) NOT NULL DEFAULT 0,
  ohada_nbv              DECIMAL(20,2) NOT NULL DEFAULT 0,
  -- IFRS basis (IAS 16 / IAS 36)
  ifrs_cost              DECIMAL(20,2) NOT NULL DEFAULT 0,
  ifrs_residual          DECIMAL(20,2) NOT NULL DEFAULT 0,
  ifrs_useful_life_months SMALLINT UNSIGNED NOT NULL DEFAULT 60,
  ifrs_method            ENUM('straight_line','declining_balance','units_of_production') NOT NULL DEFAULT 'straight_line',
  ifrs_declining_factor  DECIMAL(6,3) NOT NULL DEFAULT 1.000,
  ifrs_measurement_model ENUM('cost','revaluation') NOT NULL DEFAULT 'cost',
  ifrs_accum_depr        DECIMAL(20,2) NOT NULL DEFAULT 0,
  ifrs_revaluation_surplus DECIMAL(20,2) NOT NULL DEFAULT 0,
  ifrs_accum_impairment  DECIMAL(20,2) NOT NULL DEFAULT 0,
  ifrs_nbv               DECIMAL(20,2) NOT NULL DEFAULT 0,
  last_depr_period_id    INT UNSIGNED NULL,
  depr_start_date        DATE         NULL,
  -- componentisation (IAS 16 component depreciation)
  parent_asset_id        INT UNSIGNED NULL,
  is_component           TINYINT(1)   NOT NULL DEFAULT 0,
  component_of_label     VARCHAR(120) NULL,
  -- warranty & contracts (FR-AM-023)
  warranty_start         DATE         NULL,
  warranty_end           DATE         NULL,
  warranty_terms         VARCHAR(400) NULL,
  -- maintenance & compliance schedule (FR-AM-020 / FR-AM-022)
  next_pm_date           DATE         NULL,
  last_pm_date           DATE         NULL,
  calibration_interval_months SMALLINT UNSIGNED NULL,
  last_calibration_date  DATE         NULL,
  next_calibration_date  DATE         NULL,
  last_safety_test_date  DATE         NULL,
  next_safety_test_date  DATE         NULL,
  commissioning_done     TINYINT(1)   NOT NULL DEFAULT 0,
  commissioning_date     DATE         NULL,
  commissioning_notes    VARCHAR(500) NULL,
  -- utilisation (FR-AM-041)
  usage_hours            DECIMAL(14,2) NOT NULL DEFAULT 0,
  total_downtime_hours   DECIMAL(14,2) NOT NULL DEFAULT 0,
  -- total cost of ownership (FR-AM-032)
  total_maintenance_cost DECIMAL(20,2) NOT NULL DEFAULT 0,
  total_parts_cost       DECIMAL(20,2) NOT NULL DEFAULT 0,
  -- identification
  qr_payload             VARCHAR(200) NULL,
  barcode_value          VARCHAR(80)  NULL,
  has_rfid               TINYINT(1)   NOT NULL DEFAULT 0,
  rfid_tag               VARCHAR(80)  NULL,
  tag_printed_at         DATETIME     NULL,
  photo_path             VARCHAR(400) NULL,
  -- disposal
  disposal_id            INT UNSIGNED NULL,
  notes                  TEXT         NULL,
  created_by             INT UNSIGNED NULL,
  created_at             DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at             DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_asset_tag (org_id, asset_tag),
  UNIQUE KEY uq_asset_rfid (org_id, rfid_tag),
  KEY ix_asset_cat (org_id, category_id),
  KEY ix_asset_cc (org_id, cost_center_id),
  KEY ix_asset_status (org_id, status),
  KEY ix_asset_serial (org_id, serial_number),
  KEY ix_asset_pm (org_id, next_pm_date),
  KEY ix_asset_cal (org_id, next_calibration_date),
  KEY ix_asset_parent (parent_asset_id),
  CONSTRAINT fk_asset_org    FOREIGN KEY (org_id) REFERENCES organizations (id) ON DELETE CASCADE,
  CONSTRAINT fk_asset_cat    FOREIGN KEY (category_id) REFERENCES asset_categories (id),
  CONSTRAINT fk_asset_cc     FOREIGN KEY (cost_center_id) REFERENCES cost_centers (id) ON DELETE SET NULL,
  CONSTRAINT fk_asset_loc    FOREIGN KEY (location_id) REFERENCES asset_locations (id) ON DELETE SET NULL,
  CONSTRAINT fk_asset_parent FOREIGN KEY (parent_asset_id) REFERENCES assets (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

