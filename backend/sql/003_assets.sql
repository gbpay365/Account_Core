-- FR-AM-003 :: configurable taxonomy (UMDNS/GMDN-style) + accounting defaults
CREATE TABLE IF NOT EXISTS asset_categories (
  id                        INT UNSIGNED NOT NULL AUTO_INCREMENT,
  org_id                    INT UNSIGNED NOT NULL,
  code                      VARCHAR(30)  NOT NULL,
  name                      VARCHAR(200) NOT NULL,
  name_en                   VARCHAR(200) NULL,
  domain                    ENUM('biomedical','facility','fleet','it_office') NOT NULL,
  parent_id                 INT UNSIGNED NULL,
  taxonomy_system           ENUM('umdns','gmdn','internal','none') NOT NULL DEFAULT 'internal',
  taxonomy_code             VARCHAR(30)  NULL,
  -- GL account defaults driving automatic postings
  asset_account_id          INT UNSIGNED NULL,
  accum_depr_account_id     INT UNSIGNED NULL,
  depr_expense_account_id   INT UNSIGNED NULL,
  disposal_gain_account_id  INT UNSIGNED NULL,
  disposal_loss_account_id  INT UNSIGNED NULL,
  maintenance_account_id    INT UNSIGNED NULL,
  revaluation_surplus_account_id INT UNSIGNED NULL,
  impairment_account_id     INT UNSIGNED NULL,
  -- OHADA / SYSCOHADA statutory measurement
  ohada_useful_life_months  SMALLINT UNSIGNED NOT NULL DEFAULT 60,
  ohada_method              ENUM('straight_line','declining_balance') NOT NULL DEFAULT 'straight_line',
  ohada_declining_factor    DECIMAL(6,3) NOT NULL DEFAULT 1.000,
  ohada_salvage_pct         DECIMAL(7,4) NOT NULL DEFAULT 0,
  -- IFRS measurement (IAS 16) - may diverge from statutory
  ifrs_useful_life_months   SMALLINT UNSIGNED NOT NULL DEFAULT 60,
  ifrs_method               ENUM('straight_line','declining_balance','units_of_production') NOT NULL DEFAULT 'straight_line',
  ifrs_declining_factor     DECIMAL(6,3) NOT NULL DEFAULT 1.000,
  ifrs_residual_pct         DECIMAL(7,4) NOT NULL DEFAULT 0,
  ifrs_measurement_model    ENUM('cost','revaluation') NOT NULL DEFAULT 'cost',
  allow_component_depr      TINYINT(1)   NOT NULL DEFAULT 0,
  -- Compliance & maintenance defaults (configurable, never hard-coded)
  requires_calibration      TINYINT(1)   NOT NULL DEFAULT 0,
  calibration_interval_months SMALLINT UNSIGNED NULL,
  requires_safety_test      TINYINT(1)   NOT NULL DEFAULT 0,
  safety_test_standard      VARCHAR(40)  NULL,
  safety_interval_months    SMALLINT UNSIGNED NULL,
  pm_interval_months        SMALLINT UNSIGNED NULL,
  pm_interval_hours         INT UNSIGNED NULL,
  pm_interval_km            INT UNSIGNED NULL,
  capitalization_threshold  DECIMAL(20,2) NOT NULL DEFAULT 0,
  default_criticality       ENUM('low','medium','high','critical') NOT NULL DEFAULT 'medium',
  is_active                 TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ac_code (org_id, code),
  KEY ix_ac_domain (org_id, domain),
  KEY ix_ac_parent (parent_id),
  CONSTRAINT fk_ac_org    FOREIGN KEY (org_id) REFERENCES organizations (id) ON DELETE CASCADE,
  CONSTRAINT fk_ac_parent FOREIGN KEY (parent_id) REFERENCES asset_categories (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS asset_locations (
